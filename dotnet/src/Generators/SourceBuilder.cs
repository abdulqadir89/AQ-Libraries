using System.Text;

namespace AQ.Generators
{
    internal static class SourceBuilder
    {
        public static StringBuilder Begin(string ns)
        {
            var builder = new StringBuilder();
            builder.Append("// <auto-generated/>\n#nullable enable\n\n");
            if (ns.Length > 0)
            {
                builder.Append("namespace ").Append(ns).Append("\n{\n");
            }

            return builder;
        }

        public static string End(StringBuilder builder, string ns)
        {
            if (ns.Length > 0)
            {
                builder.Append("}\n");
            }

            return builder.ToString();
        }
    }
}
