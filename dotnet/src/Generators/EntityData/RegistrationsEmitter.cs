using System.Collections.Generic;
using System.Linq;
using System.Text;
using AQ.Generators.Snapshots;
using AQ.Generators.Tagging;
using AQ.Generators.Versioning;

namespace AQ.Generators.EntityData
{
    internal static class RegistrationsEmitter
    {
        public static bool HasOutput(GenerationInput input)
        {
            return input.SnapshotMembers.Any(m => m.Model is not null)
                || input.Snapshottable.Length > 0
                || input.VersionGroups.Length > 0
                || input.Taggables.Any(t => t.Diagnostics.Length == 0);
        }

        public static string Emit(GenerationInput input)
        {
            var snapshotWriters = GroupWriters(input.SnapshotMembers.Concat(VersionGroupEmitter.SnapshotMembers(input)), input.Snapshottable);
            var builder = new StringBuilder();
            builder.Append("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS8618, CA2255\n\n");
            builder.Append("namespace ").Append(Names.SanitizeNamespace(input.AssemblyName)).Append(".Generated\n{\n");
            builder.Append("    public static class AQGeneratedRegistrations\n    {\n");
            builder.Append("        private static readonly object Gate = new object();\n");
            builder.Append("        private static volatile bool _registered;\n\n");
            builder.Append("        public static void EnsureRegistered()\n        {\n");
            builder.Append("            if (_registered)\n            {\n                return;\n            }\n\n");
            builder.Append("            lock (Gate)\n            {\n");
            builder.Append("                if (_registered)\n                {\n                    return;\n                }\n\n");
            builder.Append("                Register();\n                _registered = true;\n            }\n        }\n\n");
            // RULE GEN-4
            builder.Append("        [global::System.Runtime.CompilerServices.ModuleInitializer]\n");
            builder.Append("        internal static void Init() => EnsureRegistered();\n\n");
            builder.Append("        private static void Register()\n        {\n");

            AppendRegisterCalls(builder, snapshotWriters, SnapshotNames.SnapshotAttributeGlobal, "WriteSnapshot");
            SnapshotEmitter.AppendRegistrations(builder, input);
            TaggableEmitter.AppendRegistrations(builder, input);

            builder.Append("        }\n");

            AppendWriterMethods(builder, snapshotWriters, "WriteSnapshot");

            builder.Append("    }\n}\n");
            return builder.ToString();
        }

        private static List<Writer> GroupWriters(IEnumerable<MemberResult> members, EquatableArray<ClassModel> classes)
        {
            var writers = new Dictionary<string, Writer>();
            foreach (var model in members.Where(m => m.Model is not null).Select(m => m.Model!).OrderBy(m => m.SortKey, System.StringComparer.Ordinal))
            {
                if (!writers.TryGetValue(model.DeclaringType, out var writer))
                {
                    writer = new Writer(model.DeclaringType);
                    writers[model.DeclaringType] = writer;
                }

                writer.Statements.AddRange(model.Statements);
            }

            foreach (var type in classes.Where(c => c.IncludeId))
            {
                if (!writers.TryGetValue(type.FullName, out var writer))
                {
                    writer = new Writer(type.FullName);
                    writers[type.FullName] = writer;
                }

                writer.IncludeId = true;
            }

            return writers.Values.OrderBy(w => w.TypeName, System.StringComparer.Ordinal).ToList();
        }

        private static void AppendRegisterCalls(StringBuilder builder, List<Writer> writers, string attribute, string prefix)
        {
            for (var i = 0; i < writers.Count; i++)
            {
                builder.Append("            ").Append(Names.EntityDataRegistry).Append('<').Append(attribute).Append(">.Register(typeof(")
                    .Append(writers[i].TypeName).Append("), ").Append(prefix).Append('_').Append(i).Append(");\n");
            }
        }

        private static void AppendWriterMethods(StringBuilder builder, List<Writer> writers, string prefix)
        {
            for (var i = 0; i < writers.Count; i++)
            {
                var writer = writers[i];
                builder.Append("\n        private static void ").Append(prefix).Append('_').Append(i)
                    .Append("(object o, global::System.Collections.Generic.IDictionary<string, object?> d)\n        {\n");
                builder.Append("            var e = (").Append(writer.TypeName).Append(")o;\n");
                if (writer.IncludeId)
                {
                    builder.Append("            d[\"id\"] = e.Id;\n");
                }

                foreach (var statement in writer.Statements)
                {
                    builder.Append("            ").Append(statement).Append('\n');
                }

                builder.Append("        }\n");
            }
        }

        private sealed class Writer
        {
            public Writer(string typeName)
            {
                TypeName = typeName;
            }

            public string TypeName { get; }

            public bool IncludeId { get; set; }

            public List<string> Statements { get; } = new List<string>();
        }
    }
}
