using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace AQ.Generators
{
    internal static class Emitter
    {
        public static string EmitRegistrations(GenerationInput input)
        {
            var snapshotWriters = GroupWriters(input.SnapshotMembers, input.Snapshottable);
            var versionedWriters = GroupWriters(input.VersionedMembers, input.Versionable);
            var builder = new StringBuilder();
            builder.Append("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS8618, CA2255\n\n");
            builder.Append("namespace ").Append(Names.SanitizeNamespace(input.AssemblyName)).Append(".Generated\n{\n");
            builder.Append("    public static class AQGeneratedRegistrations\n    {\n");
            builder.Append("        private static readonly object Gate = new object();\n");
            builder.Append("        private static volatile bool _registered;\n\n");
            builder.Append("        public static void EnsureRegistered()\n        {\n");
            builder.Append("            if (_registered)\n            {\n                return;\n            }\n\n");
            builder.Append("            lock (Gate)\n            {\n");
            builder.Append("                if (_registered)\n                {\n                    return;\n                }\n\n");
            builder.Append("                Register();\n                _registered = true;\n            }\n        }\n\n");
            // RULE GEN-4
            builder.Append("        [global::System.Runtime.CompilerServices.ModuleInitializer]\n");
            builder.Append("        internal static void Init() => EnsureRegistered();\n\n");
            builder.Append("        private static void Register()\n        {\n");

            AppendRegisterCalls(builder, snapshotWriters, Names.SnapshotAttributeGlobal, "WriteSnapshot");
            AppendRegisterCalls(builder, versionedWriters, Names.VersionedAttributeGlobal, "WriteVersioned");
            AppendExtraRegistrations(builder, input);

            builder.Append("        }\n");

            AppendWriterMethods(builder, snapshotWriters, "WriteSnapshot");
            AppendWriterMethods(builder, versionedWriters, "WriteVersioned");

            builder.Append("    }\n}\n");
            return builder.ToString();
        }

        public static bool HasOutput(GenerationInput input)
        {
            return input.SnapshotMembers.Any(m => m.Model is not null)
                || input.VersionedMembers.Any(m => m.Model is not null)
                || input.Snapshottable.Length > 0
                || input.Versionable.Length > 0;
        }

        public static string EmitSnapshotClass(ClassModel model)
        {
            var typeName = SnapshotTypeName(model);
            var builder = new StringBuilder();
            builder.Append("// <auto-generated/>\n#nullable enable\n\n");
            if (model.Namespace.Length > 0)
            {
                builder.Append("namespace ").Append(model.Namespace).Append("\n{\n");
            }

            builder.Append("    public partial class ").Append(typeName).Append(" : global::AQ.Utilities.Snapshots.EntitySnapshot\n    {\n");
            builder.Append("        public global::System.Guid ").Append(model.Name).Append("Id { get; private set; }\n");
            builder.Append("        public ").Append(model.FullName).Append("? ").Append(model.Name).Append(" { get; private set; }\n\n");
            builder.Append("        private ").Append(typeName).Append("() { }\n\n");
            builder.Append("        public static ").Append(typeName).Append(" Create(global::System.Guid entityId, int version, string data)\n");
            builder.Append("        {\n            return new ").Append(typeName).Append("() { EntityId = entityId, ").Append(model.Name).Append("Id = entityId, Version = version, Data = data };\n        }\n");
            builder.Append("    }\n");
            if (model.Namespace.Length > 0)
            {
                builder.Append("}\n");
            }

            return builder.ToString();
        }

        public static string SnapshotTypeName(ClassModel model)
        {
            return model.TypeNameOverride ?? model.Name + "Snapshot";
        }

        public static string SnapshotClassFullName(ClassModel model)
        {
            return "global::" + (model.Namespace.Length > 0 ? model.Namespace + "." : string.Empty) + SnapshotTypeName(model);
        }

        public static string EmitVersionClass(ClassModel model)
        {
            var typeName = model.Name + "Version";
            var builder = new StringBuilder();
            builder.Append("// <auto-generated/>\n#nullable enable\n\n");
            if (model.Namespace.Length > 0)
            {
                builder.Append("namespace ").Append(model.Namespace).Append("\n{\n");
            }

            builder.Append("    public sealed partial class ").Append(typeName)
                .Append(" : global::AQ.Utilities.Versioning.EntityVersion<").Append(model.UserType).Append(">\n    {\n");
            builder.Append("        public global::System.Guid ").Append(model.Name).Append("Id { get; private set; }\n");
            builder.Append("        public ").Append(model.FullName).Append("? ").Append(model.Name).Append(" { get; private set; }\n\n");
            builder.Append("        private ").Append(typeName).Append("() { }\n\n");
            builder.Append("        public static ").Append(typeName).Append(" Create(global::System.Guid ").Append(ParameterName(model.Name))
                .Append("Id, int versionNumber, string? label, string data, int? sourceVersionNumber)\n        {\n");
            builder.Append("            var version = new ").Append(typeName).Append(" { ").Append(model.Name).Append("Id = ").Append(ParameterName(model.Name)).Append("Id };\n");
            builder.Append("            version.Initialize(versionNumber, label, data, sourceVersionNumber);\n");
            builder.Append("            return version;\n        }\n\n");
            builder.Append("        public override global::System.Guid GetEntityId() => ").Append(model.Name).Append("Id;\n");
            builder.Append("    }\n");
            if (model.Namespace.Length > 0)
            {
                builder.Append("}\n");
            }

            return builder.ToString();
        }

        public static string VersionClassFullName(ClassModel model)
        {
            return "global::" + (model.Namespace.Length > 0 ? model.Namespace + "." : string.Empty) + model.Name + "Version";
        }

        private static string ParameterName(string name)
        {
            return Names.ToCamelCase(name);
        }

        private static void AppendExtraRegistrations(StringBuilder builder, GenerationInput input)
        {
            // RULE GEN-5
            foreach (var model in input.Snapshottable.OrderBy(c => c.FullName, System.StringComparer.Ordinal))
            {
                var snapshotType = SnapshotClassFullName(model);
                builder.Append("            global::AQ.Utilities.Snapshots.SnapshotRegistry.Register(new global::AQ.Utilities.Snapshots.SnapshotDescriptor(\n");
                builder.Append("                \"").Append(model.Name).Append("\", typeof(").Append(model.FullName).Append("), typeof(").Append(snapshotType).Append("),\n");
                builder.Append("                \"").Append(model.Name).Append("Id\", \"").Append(model.Name).Append("\", ").Append(model.KeepLast).Append(", ").Append(model.MaxAgeDays).Append(",\n");
                builder.Append("                static (id, version, data) => ").Append(snapshotType).Append(".Create(id, version, data)));\n");
            }

            foreach (var model in input.Versionable.Where(c => c.UserType is not null).OrderBy(c => c.FullName, System.StringComparer.Ordinal))
            {
                var versionType = VersionClassFullName(model);
                builder.Append("            global::AQ.Utilities.Versioning.VersionRegistry.Register(new global::AQ.Utilities.Versioning.VersionDescriptor(\n");
                builder.Append("                \"").Append(model.Name).Append("\", typeof(").Append(model.FullName).Append("), typeof(").Append(versionType).Append("),\n");
                builder.Append("                \"").Append(model.Name).Append("Id\", \"").Append(model.Name).Append("\",\n");
                builder.Append("                static (id, number, label, data, source) => ").Append(versionType).Append(".Create(id, number, label, data, source),\n");
                builder.Append("                static (source, id) => global::System.Linq.Queryable.Where(source.Set<").Append(versionType).Append(">(), v => v.").Append(model.Name).Append("Id == id)));\n");
            }
        }

        private static List<Writer> GroupWriters(EquatableArray<MemberResult> members, EquatableArray<ClassModel> classes)
        {
            var writers = new Dictionary<string, Writer>();
            foreach (var model in members.Where(m => m.Model is not null).Select(m => m.Model!).OrderBy(m => m.SortKey, System.StringComparer.Ordinal))
            {
                if (!writers.TryGetValue(model.DeclaringType, out var writer))
                {
                    writer = new Writer(model.DeclaringType);
                    writers[model.DeclaringType] = writer;
                }

                writer.Statements.AddRange(model.Statements);
            }

            foreach (var type in classes.Where(c => c.IncludeId))
            {
                if (!writers.TryGetValue(type.FullName, out var writer))
                {
                    writer = new Writer(type.FullName);
                    writers[type.FullName] = writer;
                }

                writer.IncludeId = true;
            }

            return writers.Values.OrderBy(w => w.TypeName, System.StringComparer.Ordinal).ToList();
        }

        private static void AppendRegisterCalls(StringBuilder builder, List<Writer> writers, string attribute, string prefix)
        {
            for (var i = 0; i < writers.Count; i++)
            {
                builder.Append("            ").Append(Names.EntityDataRegistry).Append('<').Append(attribute).Append(">.Register(typeof(")
                    .Append(writers[i].TypeName).Append("), ").Append(prefix).Append('_').Append(i).Append(");\n");
            }
        }

        private static void AppendWriterMethods(StringBuilder builder, List<Writer> writers, string prefix)
        {
            for (var i = 0; i < writers.Count; i++)
            {
                var writer = writers[i];
                builder.Append("\n        private static void ").Append(prefix).Append('_').Append(i)
                    .Append("(object o, global::System.Collections.Generic.IDictionary<string, object?> d)\n        {\n");
                builder.Append("            var e = (").Append(writer.TypeName).Append(")o;\n");
                if (writer.IncludeId)
                {
                    builder.Append("            d[\"id\"] = e.Id;\n");
                }

                foreach (var statement in writer.Statements)
                {
                    builder.Append("            ").Append(statement).Append('\n');
                }

                builder.Append("        }\n");
            }
        }

        private sealed class Writer
        {
            public Writer(string typeName)
            {
                TypeName = typeName;
            }

            public string TypeName { get; }

            public bool IncludeId { get; set; }

            public List<string> Statements { get; } = new List<string>();
        }
    }
}
