<#
.SYNOPSIS
  Keeps docs/LIBRARIES.md in sync with the code. Run from anywhere with pwsh.

.DESCRIPTION
  -Check (default)  Fails (exit 1) when the doc and the code disagree.
  -Write            Regenerates the generated block in LIBRARIES.md, then runs the checks.

  Generated block (never edit by hand), delimited by markers in LIBRARIES.md:
    <!-- BEGIN:surface --> ... <!-- END:surface -->
        The package graph: every .NET library with the AQ libraries it references and the external packages
        it pulls in, plus the React package's peer dependencies and component folders.

  Checks:
    1. Generated block equals what the code produces.
    2. Every library (.NET project under dotnet/src and the React package) is claimed by at least one
       `<!-- projects: A, B -->` marker on a section heading, and every claimed name exists.
    3. Every rule id written in LIBRARIES.md (`**ABC-12**`) appears in code as `RULE ABC-12`; ids are unique;
       every `RULE ABC-12` tag in code has a rule in the doc.
    4. Every `ADR-NNN` mentioned in code or docs resolves to docs/decisions/NNN-*.md.
    5. Every code TODO is written `TODO-NNN` and resolves to docs/todos/NNN-*.md.
    6. Relative markdown links in LIBRARIES.md / CLAUDE.md / library README.md files resolve; code fences are balanced.

  Rules for authors: see "Documentation" in the root CLAUDE.md.
#>
[CmdletBinding()]
param([switch]$Check, [switch]$Write)

$ErrorActionPreference = 'Stop'
$root      = Resolve-Path (Join-Path $PSScriptRoot '..')
$libDoc    = Join-Path $root 'docs/LIBRARIES.md'
$srcDir    = Join-Path $root 'dotnet/src'
$reactPkg  = Join-Path $root 'react/package.json'
$reactSrc  = Join-Path $root 'react/src'
$errors    = New-Object System.Collections.Generic.List[string]
function Fail($m) { $errors.Add($m) | Out-Null }

if (-not (Test-Path $libDoc)) { Write-Host 'docs/LIBRARIES.md not found'; exit 1 }
$doc = Get-Content $libDoc -Raw

# ---------- generated: surface ----------
$projects = Get-ChildItem $srcDir -Recurse -Filter *.csproj |
    Where-Object { $_.FullName -notmatch '[\\/](bin|obj)[\\/]' } |
    ForEach-Object {
        $xml = [xml](Get-Content $_.FullName -Raw)
        $name = [IO.Path]::GetFileNameWithoutExtension($_.Name)
        $projectRefs = @($xml.SelectNodes('//ProjectReference') | ForEach-Object { [IO.Path]::GetFileNameWithoutExtension(($_.Include -replace '\\', '/')) } | Sort-Object -Unique)
        $packageRefs = @($xml.SelectNodes('//PackageReference') | ForEach-Object { $_.Include } | Sort-Object -Unique)
        [pscustomobject]@{
            Name     = $name
            Folder   = [IO.Path]::GetRelativePath($root, $_.DirectoryName) -replace '\\', '/'
            Projects = $projectRefs
            Packages = $packageRefs
        }
    } | Sort-Object Name

$gen = New-Object System.Text.StringBuilder
[void]$gen.AppendLine('_Generated by `scripts/docs-sync.ps1 -Write` from the project files. Do not edit._')
[void]$gen.AppendLine('')
[void]$gen.AppendLine('**.NET libraries** (`dotnet/src`)')
[void]$gen.AppendLine('')
[void]$gen.AppendLine('| Library | Folder | AQ libraries it references | External packages |')
[void]$gen.AppendLine('|---|---|---|---|')
foreach ($p in $projects) {
    $refs = if ($p.Projects.Count) { $p.Projects -join ', ' } else { 'none' }
    $pk   = if ($p.Packages.Count) { $p.Packages -join ', ' } else { 'none' }
    [void]$gen.AppendLine("| $($p.Name) | $($p.Folder) | $refs | $pk |")
}
[void]$gen.AppendLine('')

$react = Get-Content $reactPkg -Raw | ConvertFrom-Json
$peers = @($react.peerDependencies.PSObject.Properties | ForEach-Object { "$($_.Name) $($_.Value)" })
$runtime = @(if ($react.PSObject.Properties.Name -contains 'dependencies') { $react.dependencies.PSObject.Properties | ForEach-Object { $_.Name } })
$components = @(Get-ChildItem (Join-Path $reactSrc 'mantine') -Directory | ForEach-Object { $_.Name } | Sort-Object)
$utils = @(Get-ChildItem (Join-Path $reactSrc 'utils') -File -Filter *.ts | Where-Object { $_.Name -ne 'index.ts' } | ForEach-Object { $_.BaseName } | Sort-Object)
[void]$gen.AppendLine("**React package** (``$($react.name)``, ``react/src``)")
[void]$gen.AppendLine('')
[void]$gen.AppendLine('- Component folders (`src/mantine`): ' + ($components -join ', '))
[void]$gen.AppendLine('- Utilities (`src/utils`): ' + ($utils -join ', '))
[void]$gen.AppendLine('- Runtime dependencies: ' + $(if ($runtime.Count) { $runtime -join ', ' } else { 'none' }))
[void]$gen.AppendLine('- Peer dependencies: ' + ($peers -join ', '))
$block = $gen.ToString().TrimEnd()

$beginTag = '<!-- BEGIN:surface -->'; $endTag = '<!-- END:surface -->'
$pattern = [regex]::Escape($beginTag) + '(?s).*?' + [regex]::Escape($endTag)
if ($doc -notmatch $pattern) {
    Fail "LIBRARIES.md is missing the $beginTag ... $endTag markers"
} else {
    $replacement = "$beginTag`n$block`n$endTag"
    if ($Write) {
        $doc = [regex]::Replace($doc, $pattern, { param($m) $replacement })
        [System.IO.File]::WriteAllText($libDoc, $doc, (New-Object System.Text.UTF8Encoding($false)))
        Write-Host 'Regenerated surface block.'
    } else {
        $current  = [regex]::Match($doc, $pattern).Value -replace "`r`n", "`n"
        $expected = $replacement -replace "`r`n", "`n"
        if ($current.Trim() -ne $expected.Trim()) { Fail 'surface block is out of date, run scripts/docs-sync.ps1 -Write' }
    }
}

# ---------- check: library coverage ----------
$claimed = @()
foreach ($m in [regex]::Matches($doc, '<!--\s*projects:\s*([^>]*?)\s*-->')) {
    $claimed += $m.Groups[1].Value -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ }
}
$actual = @($projects | ForEach-Object { $_.Name }) + @($react.name)
foreach ($n in $actual)  { if ($claimed -notcontains $n) { Fail "library not described in LIBRARIES.md (add to a '<!-- projects: -->' marker): $n" } }
foreach ($n in $claimed) { if ($actual -notcontains $n)  { Fail "LIBRARIES.md claims a library that does not exist: $n" } }

# ---------- check: react runtime dependencies (RCT-1) ----------
if ($runtime.Count -gt 0) { Fail "react/package.json declares runtime dependencies ($($runtime -join ', ')); RCT-1 allows peer dependencies only" }

# ---------- check: rule ids ----------
$docBody = [regex]::Replace($doc, [regex]::Escape($beginTag) + '(?s).*?' + [regex]::Escape($endTag), '')
$ruleIds = [regex]::Matches($docBody, '\*\*([A-Z]{3}-\d+)\*\*') | ForEach-Object { $_.Groups[1].Value }
$ruleIds | Group-Object | Where-Object Count -gt 1 | ForEach-Object { Fail "rule id defined more than once: $($_.Name)" }

Push-Location $root
try {
    $tags = @(git grep -ohE --untracked 'RULE [A-Z]{3}-[0-9]+' -- . ':!*.md' ':!scripts' ':!*/node_modules/*' 2>$null | ForEach-Object { ($_ -replace '^RULE ', '').Trim() }) | Sort-Object -Unique
} finally { Pop-Location }
foreach ($id in ($ruleIds | Sort-Object -Unique)) {
    if ($tags -notcontains $id) { Fail "rule $id is in LIBRARIES.md but no 'RULE $id' comment exists in code (rule removed? delete it from the doc)" }
}
foreach ($id in $tags) {
    if ($ruleIds -notcontains $id) { Fail "code has 'RULE $id' but LIBRARIES.md defines no such rule (rule removed from the doc? remove the tag)" }
}

# ---------- check: ADR refs ----------
$adrFiles = @(Get-ChildItem (Join-Path $root 'docs/decisions') -Filter '*.md' -ErrorAction SilentlyContinue | ForEach-Object { $_.Name })
function Test-Adr($id, $where) {
    $n = $id -replace 'ADR-', ''
    if (-not ($adrFiles | Where-Object { $_ -like "$n-*" })) { Fail "ADR-$n referenced in $where has no file in docs/decisions/" }
}
Push-Location $root
try {
    git grep -nE --untracked 'ADR-[0-9]{3}' -- . ':!docs/decisions' ':!scripts' ':!*/node_modules/*' 2>$null | ForEach-Object {
        if ($_ -match '^(.+?):(\d+):.*?(ADR-\d{3})') { Test-Adr $Matches[3] "$($Matches[1]):$($Matches[2])" }
    }
} finally { Pop-Location }

# ---------- check: TODO ids ----------
$todoFiles = @(Get-ChildItem (Join-Path $root 'docs/todos') -Filter '*.md' -ErrorAction SilentlyContinue | ForEach-Object { $_.Name })
Push-Location $root
try {
    git grep -nE --untracked '\bTODO' -- . ':!docs' ':!scripts' ':!*.md' ':!*/node_modules/*' ':!*package-lock.json' ':!*/Migrations/*' 2>$null | ForEach-Object {
        if ($_ -notmatch '^(.+?):(\d+):(.*)$') { return }
        $where = "$($Matches[1]):$($Matches[2])"
        $line = $Matches[3]
        if ($line -notmatch 'TODO-\d{3}') { Fail "bare TODO at $where; use 'TODO-NNN' and add docs/todos/NNN-*.md"; return }
        foreach ($m in [regex]::Matches($line, 'TODO-(\d{3})')) {
            $n = $m.Groups[1].Value
            if (-not ($todoFiles | Where-Object { $_ -like "$n-*" })) { Fail "TODO-$n at $where has no file in docs/todos/" }
        }
    }
} finally { Pop-Location }

# ---------- check: links + fences ----------
$skip = 'node_modules|[\\/]bin[\\/]|[\\/]obj[\\/]|[\\/]dist[\\/]|[\\/]\.claude[\\/]worktrees[\\/]'
$mdFiles = @($libDoc) +
    @(Get-ChildItem $root -Recurse -Filter CLAUDE.md -File -ErrorAction SilentlyContinue | Where-Object { $_.FullName -notmatch $skip } | ForEach-Object { $_.FullName }) +
    @(Get-ChildItem $srcDir -Recurse -Filter README.md -File -ErrorAction SilentlyContinue | Where-Object { $_.FullName -notmatch $skip } | ForEach-Object { $_.FullName }) +
    @(Get-ChildItem (Join-Path $root 'docs') -Recurse -Filter *.md -File -ErrorAction SilentlyContinue | Where-Object { $_.FullName -ne $libDoc -and $_.FullName -notmatch '[\\/]decisions[\\/]README\.md$' } | ForEach-Object { $_.FullName })
foreach ($f in ($mdFiles | Sort-Object -Unique)) {
    $text = Get-Content $f -Raw
    $dir = Split-Path $f
    foreach ($m in [regex]::Matches($text, '\]\(((?!https?:|mailto:|#)[^)\s]+)\)')) {
        $target = ($m.Groups[1].Value -split '#')[0]
        if (-not $target) { continue }
        if (-not (Test-Path (Join-Path $dir $target))) { Fail "broken link in $([IO.Path]::GetRelativePath($root, $f)): $target" }
    }
    $fences = ([regex]::Matches($text, '(?m)^```')).Count
    if ($fences % 2 -ne 0) { Fail "unbalanced code fences in $([IO.Path]::GetRelativePath($root, $f))" }
}

# ---------- result ----------
if ($errors.Count -gt 0) {
    Write-Host "docs-sync: $($errors.Count) problem(s)" -ForegroundColor Red
    $errors | ForEach-Object { Write-Host "  - $_" }
    exit 1
}
Write-Host "docs-sync: OK ($($actual.Count) libraries, $(@($ruleIds | Sort-Object -Unique).Count) rules)" -ForegroundColor Green
exit 0
